using UsersManager.Shared;

namespace UsersManager.Client
{
    
    // ============================================================
    // החוזה של שירות ההתחברות בצד הלקוח.
    //
    // הרכיבים תלויים בממשק הזה ולא במימוש, ולכן אפשר להחליף את
    // מנגנון ההתחברות בלי לגעת במסכים
    // ============================================================
    public interface IAuthenticationService
    {
        // מופעל בכל שינוי במצב ההתחברות. רכיב שנרשם אליו יכול
        // לרענן את עצמו כשמשתמש נכנס או יוצא. חובה להתנתק ממנו
        // ב-Dispose, אחרת הרכיב יישאר מוחזק בזיכרון
        event Action OnAuthenticationStateChanged;

        // פרטי המשתמש המחובר מתוך התביעות, או null אם אין כזה
        Task<User> GetUserFromClaimAsync();

        // התנתקות: פסילת הטוקן בשרת וחזרה לפורטל"מ
        Task Logout();
        
        // ההתחברות דרך פורטל"מ. מחזיר false גם כשמפנים את
        // המשתמש לפורטל"מ - כלומר false אינו בהכרח שגיאה
        Task<bool> LoginWithPortelem();

    }
}

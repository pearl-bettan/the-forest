namespace UsersManager.Shared;

// ============================================================
// שורת משתמש כפי שהיא יושבת בטבלת Users של המחולל.
//
// מחזיקה את שני המזהים גם יחד: המזהה הפנימי שהמחולל מייצר,
// והמזהה שהגיע מפורטלם. ההפרדה הזו היא מה שמאפשר לזהות
// משתמש שחזר, גם אם שינה את הדוא"ל בפורטלם.
// אינה עוברת ללקוח - ללקוח נשלחת User מ-Shared
// ============================================================
public class PortelemUser
{
    // המזהה הפנימי של המחולל, מפתח ראשי בטבלה
    public int Id { get; set; }

    public string FirstName { get; set; }

    public string LastName { get; set; }

    public string Email { get; set; }

    // המזהה של המשתמש בפורטלם, מתוך תביעת sub שבטוקן.
    // עמודה ייחודית בטבלה, ולכן ניסיון להוסיף אותו פעמיים נכשל
    public int PortelemId { get; set; }
}
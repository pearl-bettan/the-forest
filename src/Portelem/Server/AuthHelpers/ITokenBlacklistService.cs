namespace UsersManager.Server
{    
    // ============================================================
    // החוזה של רשימת הטוקנים השחורה.
    //
    // JWT תקף עד שפג תוקפו, ולכן אין דרך "לבטל" אותו מצד השרת
    // בלי לנהל רשימה של טוקנים שנפסלו. כל טוקן שמשתמש התנתק
    // איתו נכנס לרשימה, וכל בקשה נבדקת מולה.
    //
    // לא לגעת - אבטחת משתמשים
    // ============================================================
    public interface ITokenBlacklistService
    {
        // מוסיף טוקן לרשימה השחורה, בהתנתקות
        void AddToBlacklist(string token);

        // בודק אם הטוקן נפסל. נקרא בכל בקשה מאומתת
        bool IsBlacklisted(string token);

        // מנקה מהרשימה טוקנים שתוקפם פג ממילא, כדי שהיא
        // לא תגדל ללא הגבלה. מופעל על ידי שירות הרקע
        void RemoveExpiredTokens();
    }
}
